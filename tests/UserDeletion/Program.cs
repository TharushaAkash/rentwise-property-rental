using System.Security.Claims;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Mvc;
using Microsoft.Data.Sqlite;
using Microsoft.EntityFrameworkCore;
using RentWise.API.Data;
using RentWise.API.Modules.Users;
using RentWise.API.Modules.Users.Controllers;
using RentWise.API.Modules.PropertyManagement.Entities;
using RentWise.API.Modules.TenantMatching.Entities;

await using var connection = new SqliteConnection("Data Source=:memory:");
await connection.OpenAsync();
await using var db = new ApplicationDbContext(new DbContextOptionsBuilder<ApplicationDbContext>().UseSqlite(connection).Options);
await db.Database.EnsureCreatedAsync();
var admin = new User { Name="Admin", Email="admin@fixture.invalid", Role="Admin" };
var owner = new User { Name="Owner", Email="owner@fixture.invalid", Role="PropertyOwner" };
var tenant = new User { Name="Tenant", Email="tenant@fixture.invalid", Role="Tenant" };
var otherOwner = new User { Name="Other", Email="other@fixture.invalid", Role="PropertyOwner" };
var property = new Property { OwnerId=owner.Id, Title="Fixture", Address="Malabe" };
var otherProperty = new Property { OwnerId=otherOwner.Id, Title="Other", Address="Colombo" };
db.AddRange(admin, owner, tenant, otherOwner, property, otherProperty);
await db.SaveChangesAsync();
AuthController Controller() => new(null!, db, null!, null!, null!) { ControllerContext = new ControllerContext { HttpContext = new DefaultHttpContext { User = new ClaimsPrincipal(new ClaimsIdentity(new[] { new Claim(ClaimTypes.NameIdentifier, admin.Id.ToString()), new Claim(ClaimTypes.Role, "Admin") }, "fixture")) } } };
var checks = 0;
void Check(bool success, string description) { if (!success) throw new Exception(description); checks++; }
Check(await Controller().DeleteUser(admin.Id) is BadRequestObjectResult, "Admin cannot delete self");
Check(await Controller().DeleteUser(Guid.NewGuid()) is NotFoundObjectResult, "Missing user returns 404");
db.PropertyApplications.Add(new PropertyApplication { PropertyId=otherProperty.Id, TenantId=tenant.Id });
await db.SaveChangesAsync();
Check(await Controller().DeleteUser(tenant.Id) is OkObjectResult, "Tenant with booking can be deleted");
Check(!await db.PropertyApplications.AnyAsync(), "Tenant booking removed");
Check(await db.Properties.AnyAsync(p=>p.Id==otherProperty.Id), "Other owner's property retained");
var secondTenant = new User { Name="Tenant2", Email="tenant2@fixture.invalid", Role="Tenant" };
db.Users.Add(secondTenant);
db.PropertyApplications.Add(new PropertyApplication { PropertyId=property.Id, TenantId=secondTenant.Id });
db.SavedProperties.Add(new SavedProperty { PropertyId=property.Id, TenantProfileId=secondTenant.Id });
db.DocumentReviewRequests.Add(new DocumentReviewRequest { PropertyId=property.Id, OwnerId=owner.Id, AdminId=admin.Id, Message="Proof" });
db.VerificationRecords.Add(new VerificationRecord { PropertyId=otherProperty.Id, AdminId=admin.Id, Comments="Other owner's history" });
await db.SaveChangesAsync();
Check(await Controller().DeleteUser(owner.Id) is OkObjectResult, "Owner with booked property can be deleted");
Check(!await db.PropertyApplications.AnyAsync() && !await db.SavedProperties.AnyAsync() && !await db.DocumentReviewRequests.AnyAsync(), "Related booking, saved, review records removed");
Check(await db.Users.AnyAsync(u=>u.Id==secondTenant.Id) && await db.Properties.AnyAsync(p=>p.Id==otherProperty.Id), "Unrelated users and properties retained");
var operatorUser = new User { Name="Operator", Email="operator@fixture.invalid", Role="Admin" };
db.Users.Add(operatorUser);
var history = new VerificationRecord { PropertyId=otherProperty.Id, AdminId=operatorUser.Id, Comments="Retain history" };
db.VerificationRecords.Add(history);
await db.SaveChangesAsync();
Check(await Controller().DeleteUser(operatorUser.Id) is OkObjectResult, "Referenced administrator can be deleted");
Check(await db.VerificationRecords.AnyAsync(v=>v.Id==history.Id && v.AdminId==null), "Verification history retained without removed admin");
Console.WriteLine($"PASS: {checks} user deletion checks (isolated SQLite)");
